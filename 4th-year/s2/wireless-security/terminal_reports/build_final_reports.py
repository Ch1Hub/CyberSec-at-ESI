#!/usr/bin/env python3
"""Build final lab PDF reports with embedded terminal screenshots."""

from fpdf import FPDF
from fpdf.enums import XPos, YPos
import os

# ── Fonts ───────────────────────────────────────────────────────────────────
FONT_SANS_REG   = "/usr/share/fonts/liberation-sans-fonts/LiberationSans-Regular.ttf"
FONT_SANS_BOLD  = "/usr/share/fonts/liberation-sans-fonts/LiberationSans-Bold.ttf"
FONT_SANS_ITALIC= "/usr/share/fonts/liberation-sans-fonts/LiberationSans-Italic.ttf"

class LabReportPDF(FPDF):
    def __init__(self):
        super().__init__(unit="mm", format="A4")
        self.set_auto_page_break(auto=True, margin=20)
        for name, style, path in [("Sans","",FONT_SANS_REG),("Sans","B",FONT_SANS_BOLD),("Sans","I",FONT_SANS_ITALIC)]:
            self.add_font(name, style, path, uni=True)

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("Sans", "", 8)
        self.set_text_color(120,120,120)
        self.cell(0, 5, "Ecole Superieure en Informatique, Sidi Bel Abbes  --  Wireless and Mobile Network Security  --  Cys 2SC",
                  align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(200,200,200)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(2)

    def footer(self):
        self.set_y(-12)
        self.set_font("Sans", "I", 8)
        self.set_text_color(150,150,150)
        self.cell(0, 8, f"Page {self.page_no()}", align="C")

    def cover(self, lab_num, title):
        self.add_page()
        self.set_font("Sans", "B", 22)
        self.set_text_color(30,30,30)
        self.ln(60)
        self.cell(0, 14, f"Lab {lab_num}: {title}", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_font("Sans", "", 12)
        self.set_text_color(80,80,80)
        self.cell(0, 10, "Wireless and Mobile Network Security", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.cell(0, 10, "Cys 2SC", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(20)
        self.set_font("Sans", "B", 12)
        self.cell(0, 8, "Youcef Chihab Eddine Chikhaoui", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(30)

    def section_title(self, num, title):
        self.ln(6)
        self.set_font("Sans", "B", 14)
        self.set_text_color(30,30,30)
        self.cell(0, 10, f"{num}.  {title}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(30,30,30)
        self.line(15, self.get_y(), 195, self.get_y())
        self.ln(3)

    def subsection(self, title):
        self.ln(4)
        self.set_font("Sans", "B", 12)
        self.set_text_color(50,50,50)
        self.cell(0, 8, title, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1)

    def body_text(self, text):
        self.set_font("Sans", "", 10)
        self.set_text_color(50,50,50)
        self.multi_cell(0, 6, text)
        self.ln(2)

    def embed_image(self, img_path, caption):
        if not os.path.exists(img_path):
            self.body_text(f"[Image not found: {img_path}]")
            return
        # Check available width
        img_w = 180
        img_h = img_w * 0.6  # approximate ratio
        if self.get_y() + img_h > 270:
            self.add_page()
        self.image(img_path, x=15, y=self.get_y(), w=img_w)
        self.ln(img_h + 3)
        self.set_font("Sans", "I", 9)
        self.set_text_color(100,100,100)
        self.cell(0, 5, f"Figure: {caption}", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(4)


# ── LAB 1 REPORT ────────────────────────────────────────────────────────────
def build_lab1():
    pdf = LabReportPDF()
    img_dir = "/home/chihab/Documents/cys2CS/s2/wirelessNet/terminal_reports/lab1_images"
    pdf.cover(1, "WEP (Wired Equivalent Privacy) Encryption")

    pdf.section_title("1", "Introduction")
    pdf.body_text("""Wired Equivalent Privacy (WEP) is part of the IEEE 802.11 standard designed to secure wireless network traffic. It uses the RC4 stream cipher with a static key (40 or 104 bits) concatenated with a 24-bit Initialization Vector (IV) to encrypt data. Although WEP has been superseded by WPA and WPA2/3 due to serious vulnerabilities, understanding its mechanics is essential for grasping the evolution of wireless security.""")

    pdf.section_title("2", "WEP Encryption Process")
    pdf.body_text("""The WEP encryption workflow consists of three main stages: pre-processing, RC4 keystream generation, and final encryption.""")

    pdf.subsection("2.1  Pre-Processing")
    pdf.body_text("""First, a 32-bit Integrity Check Value (ICV) is computed using the CRC-32 algorithm over the plaintext. The ICV is appended to the plaintext, forming the payload to be encrypted. Second, a 24-bit IV is generated by the sender and concatenated with the shared secret key (40 or 104 bits) to create the RC4 seed.""")

    pdf.subsection("2.2  RC4 Algorithm")
    pdf.body_text("""The RC4 seed (IV || secret key) feeds the Key Scheduling Algorithm (KSA), which initialises and permutes a 256-byte state array (S-box). The Pseudo-Random Generation Algorithm (PRGA) then walks through the S-box to generate a keystream whose length equals (plaintext + ICV).""")

    pdf.subsection("2.3  Final Encryption")
    pdf.body_text("""The keystream is XORed bitwise with (plaintext + ICV) to produce the ciphertext. The transmitted WEP frame consists of the IV (sent in clear) followed by the ciphertext.""")

    pdf.section_title("3", "Manual Application")
    pdf.body_text("""We apply the WEP process manually to the input data 10101010 (0xAA) using the generator polynomial 10011 (X^4 + X + 1).""")

    pdf.subsection("Step 1 -- CRC-32 Computation (MSB First)")
    pdf.embed_image(f"{img_dir}/lab1_crc_msb.png", "Terminal output: CRC-32 computation using MSB-first binary division")

    pdf.subsection("Step 2 -- CRC-32 Computation (LSB First / WEP Order)")
    pdf.embed_image(f"{img_dir}/lab1_crc_lsb.png", "Terminal output: CRC-32 computation using LSB-first reflection")

    pdf.subsection("Step 3 -- RC4 KSA, PRGA and XOR Encryption")
    pdf.embed_image(f"{img_dir}/lab1_rc4_encrypt.png", "Terminal output: RC4 keystream generation and WEP frame construction")

    pdf.section_title("4", "Machine Implementation")
    pdf.body_text("""A Python script was written to reproduce the entire WEP encryption pipeline step by step. The script computes CRC-32 ICV using zlib, implements RC4 KSA and PRGA, and performs XOR encryption.""")
    pdf.embed_image(f"{img_dir}/lab1_full_impl.png", "Terminal output: Full Python WEP encryption script execution")

    pdf.section_title("5", "Results and Analysis")
    pdf.body_text("""The manual calculation and the Python implementation yield identical results, confirming the correctness of the WEP encryption pipeline. The CRC-32 ICV guarantees data integrity at the link layer, while the RC4 stream cipher provides confidentiality. However, the 24-bit IV is transmitted in clear and repeats after approximately 16 million frames, enabling the well-known Fluhrer-Mantin-Shamir (FMS) attack. This weakness, combined with the static nature of the WEP key, explains why WEP was deprecated in favor of WPA/WPA2.""")

    out = "/home/chihab/Documents/cys2CS/s2/wirelessNet/Lab1_WEP_Encryption_Report.pdf"
    pdf.output(out)
    print(f"  Created: {out}")


