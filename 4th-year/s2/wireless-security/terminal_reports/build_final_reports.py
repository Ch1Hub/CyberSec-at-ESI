def build_lab3():
    pdf = LabReportPDF()
    img_dir = "/home/chihab/Documents/cys2CS/s2/wirelessNet/terminal_reports/lab3_images"
    pdf.cover(3, "WPA/WPA2 Exploitation")

    pdf.section_title("1", "Introduction")
    pdf.body_text("""This laboratory investigates the cryptographic weaknesses of the IEEE 802.11i (WPA2-PSK) protocol. While WPA2 encrypts traffic with AES/CCMP, the 4-way handshake that derives the Pairwise Transient Key (PTK) from the Pre-Shared Key (PSK) is vulnerable to offline dictionary attacks. Capturing the EAPOL frames allows an attacker to test passphrase candidates against the MIC without interacting with the live network.""")

    pdf.section_title("2", "Environment Setup")
    pdf.body_text("""Software: VirtualBox, Kali Linux, Wireshark, aircrack-ng suite. Hardware: WiFi adapter with monitor mode and frame injection support, Access Point configured with WPA2-PSK.""")

    pdf.section_title("3", "Configuration Steps")

    pdf.subsection("Step 1 -- Enable Monitor Mode")
    pdf.embed_image(f"{img_dir}/lab3_monitor.png", "Terminal output: Enabling monitor mode")

    pdf.subsection("Step 2 -- Identify the Target WPA2 Network")
    pdf.body_text("""Airodump-ng scans for WPA/WPA2 networks. The target BSSID, channel, and ESSID are noted.""")
    pdf.embed_image(f"{img_dir}/lab3_scan.png", "Terminal output: Identifying WPA2 target network HomeLab_2G")

    pdf.subsection("Step 3 -- Capture the 4-Way Handshake")
    pdf.body_text("""Airodump-ng is locked onto the target channel and BSSID. The handshake occurs when a legitimate client associates or re-associates with the AP.""")
    pdf.embed_image(f"{img_dir}/lab3_handshake_wait.png", "Terminal output: Waiting for 4-way handshake capture")

    pdf.subsection("Step 4 -- Deauthentication Attack")
    pdf.body_text("""To force a re-authentication, a deauthentication attack is launched against a connected client. This causes the client to reconnect, triggering a new 4-way handshake.""")
    pdf.embed_image(f"{img_dir}/lab3_deauth.png", "Terminal output: Sending deauthentication frames")

    pdf.subsection("Step 5 -- Handshake Captured")
    pdf.body_text("""After the client reconnects, the complete 4-way handshake is captured and stored in the pcap file.""")
    pdf.embed_image(f"{img_dir}/lab3_handshake_ok.png", "Terminal output: 4-way handshake successfully captured")

    pdf.subsection("Step 6 -- Dictionary Attack with aircrack-ng")
    pdf.body_text("""Aircrack-ng tests each candidate passphrase from the wordlist by re-computing the PTK and comparing the derived MIC with the value captured in EAPOL Message 2.""")
    pdf.embed_image(f"{img_dir}/lab3_crack_success.png", "Terminal output: WPA2 passphrase recovered via dictionary attack")

    pdf.subsection("Step 7 -- Decrypt Captured Traffic")
    pdf.body_text("""With the recovered passphrase, airdecap-ng derives the PTK and decrypts all captured WPA2 data frames.""")
    pdf.embed_image(f"{img_dir}/lab3_decrypt.png", "Terminal output: Decrypting WPA2 traffic with airdecap-ng")

    pdf.section_title("4", "Results and Analysis")
    pdf.body_text("""The WPA2-PSK passphrase was recovered in approximately 2 minutes using the rockyou.txt wordlist (14 million common passwords). The success of the attack hinges entirely on the entropy of the passphrase: weak or dictionary-based passphrases are cracked almost instantly. The 4-way handshake does not include rate-limiting or lockout mechanisms, allowing unlimited offline guesses. The PBKDF2-SHA1 iteration count (4096) is low by modern standards and can be computed at millions of candidates per second on a GPU using hashcat. Once the PSK is known, the attacker can derive the PTK and decrypt all captured traffic.""")

    pdf.section_title("5", "Defensive Recommendations")
    pdf.body_text("""To mitigate WPA2-PSK dictionary attacks: use a random passphrase of at least 20 characters (uppercase, lowercase, digits, symbols). Prefer WPA3-SAE (Simultaneous Authentication of Equals), which replaces PSK with a password-authenticated key exchange providing forward secrecy and resistance to offline dictionary attacks. In enterprise environments, deploy WPA2-Enterprise (802.1X / EAP-TLS) so that each user has a unique credential. Enable 802.11w (Protected Management Frames) to prevent deauthentication attacks.""")

    out = "/home/chihab/Documents/cys2CS/s2/wirelessNet/Lab3_WPA_WPA2_Exploitation_Report.pdf"
    pdf.output(out)
    print(f"  Created: {out}")


