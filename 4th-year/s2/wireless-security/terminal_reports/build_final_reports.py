def build_lab2():
    pdf = LabReportPDF()
    img_dir = "/home/chihab/Documents/cys2CS/s2/wirelessNet/terminal_reports/lab2_images"
    pdf.cover(2, "WEP Exploitation")

    pdf.section_title("1", "Introduction")
    pdf.body_text("""This laboratory explores practical attacks against WEP-protected wireless networks. WEP suffers from multiple cryptographic and protocol-level weaknesses: a short 24-bit IV, a static shared key, and a weak CRC-32 integrity mechanism. By capturing a sufficient number of data frames, an attacker can recover the WEP key offline using statistical methods implemented in tools such as aircrack-ng.""")

    pdf.section_title("2", "Environment Setup")
    pdf.body_text("""Software: VirtualBox, Kali Linux, Wireshark, aircrack-ng suite. Hardware: WiFi adapter compatible with monitor mode (Alfa AWUS036NHA), Access Point configured with WEP encryption.""")

    pdf.section_title("3", "Configuration Steps")

    pdf.subsection("Step 1 -- Enable Monitor Mode")
    pdf.body_text("""The wireless interface is identified and switched from managed mode to monitor mode so that all 802.11 frames in the vicinity can be captured.""")
    pdf.embed_image(f"{img_dir}/lab2_monitor_mode.png", "Terminal output: Enabling monitor mode with airmon-ng")

    pdf.subsection("Step 2 -- Discover WEP Networks")
    pdf.body_text("""Airodump-ng scans the 2.4 GHz band and filters for networks using WEP encryption. The BSSID, channel, and ESSID of the target are recorded.""")
    pdf.embed_image(f"{img_dir}/lab2_scan.png", "Terminal output: Scanning for WEP networks with airodump-ng")

    pdf.subsection("Step 3 -- Capture IVs from the Target AP")
    pdf.body_text("""Airodump-ng is focused on the target BSSID and channel. The --ivs flag stores only IV packets. In a second terminal, ARP replay injection is used to generate traffic and collect IVs faster.""")
    pdf.embed_image(f"{img_dir}/lab2_capture.png", "Terminal output: Capturing IVs from target AP DJAWEB_B771")

    pdf.subsection("Step 4 -- ARP Replay Injection")
    pdf.body_text("""Aireplay-ng -3 performs ARP request replay to stimulate traffic generation. However, in this lab the target network was inactive and no ARP requests were detected, severely limiting IV collection.""")
    pdf.embed_image(f"{img_dir}/lab2_arp_replay.png", "Terminal output: Attempting ARP replay injection")

    pdf.subsection("Step 5 -- Crack the WEP Key")
    pdf.body_text("""Once approximately 5,000--20,000 unique IVs have been captured, aircrack-ng performs a statistical attack. In this session, only 451 IVs were available, which is insufficient for key recovery.""")
    pdf.embed_image(f"{img_dir}/lab2_crack_fail.png", "Terminal output: aircrack-ng fails due to insufficient IVs")

    pdf.section_title("4", "Results and Analysis")
    pdf.body_text("""The WEP key could NOT be recovered because the capture file contains only 451 IVs -- far below the ~5,000 minimum required for PTW or KoreK statistical attacks. The original lab router (configured with WEP) is no longer accessible; only historical capture data remains. Key observations: the 24-bit IV space is exhausted quickly, leading to IV reuse. ARP replay injection can artificially generate traffic on active networks. Once sufficient IVs are collected, the key can be recovered in minutes. The CRC-32 ICV does not protect against intentional frame modification.""")
    pdf.embed_image(f"{img_dir}/lab2_capinfos.png", "Terminal output: Capture file metadata from capinfos")

    pdf.section_title("5", "Defensive Recommendations")
    pdf.body_text("""WEP should never be used in production. The minimum recommended standard is WPA2-PSK with AES/CCMP and a strong passphrase (>= 20 random characters). For enterprise environments, WPA2-Enterprise (802.1X / RADIUS) or WPA3-SAE provides significantly stronger authentication and forward secrecy.""")

    out = "/home/chihab/Documents/cys2CS/s2/wirelessNet/Lab2_WEP_Exploitation_Report.pdf"
    pdf.output(out)
    print(f"  Created: {out}")


